import {readFileSync,existsSync,readdirSync} from 'node:fs';
import {resolve} from 'node:path';
const base=resolve(import.meta.dirname,'..');
const text=(name)=>readFileSync(resolve(base,name),'utf8');
const pkg=JSON.parse(text('package.json'));
const config=JSON.parse(text('wrangler.jsonc'));
const fail=(reason)=>{console.error('Cloudflare preflight FAILED:',reason);process.exitCode=1;};
const check=(condition,reason)=>{if(!condition)fail(reason);};
check(pkg.dependencies.react.startsWith('19.'),'Must use supported React 19, not the old preview runtime');
check(pkg.dependencies['react-dom']===pkg.dependencies.react,'React and ReactDOM runtime versions must match');
check(config.assets?.run_worker_first===true,'The Worker must authenticate requests before all static assets');
check(config.assets?.binding==='ASSETS'&&config.assets?.directory==='./site','Cloudflare static assets binding missing');
check(config.d1_databases?.length===1&&config.d1_databases[0].binding==='DB','D1 DB binding missing');
check(text('src/cloud/access.mjs').includes('Cf-Access-Jwt-Assertion'),'Access JWT must be cryptographically validated');
check(text('src/cloud/handler.mjs').includes('await ensureSchema(db)'),'First-run D1 bootstrap missing');
check(text('src/web/main.tsx').includes("'/api/auth/session'"),'The frontend must require Cloudflare Access');
check(!text('src/web/main.tsx').includes('authScreen('),'Do not ship old password/recovery flows in the new frontend');
check(!text('index.html').includes('server-mode.js'),'Old local-only mode should not ship');
check(!existsSync(resolve(base,'public/vendor')),'React 16 preview must not ship in public assets');
check(!existsSync(resolve(base,'public/assets')),'Old pre-bundled frontend should not ship');
check(existsSync(resolve(base,'migrations/0001_initial.sql')),'Initial database schema missing');
check(!text('src/cloud/handler.mjs').includes('Docker'),'Worker should not require a Docker backend');
if(!process.exitCode)console.log('Cloudflare static preflight: PASS');
